package de.tum.cit.aet.artemis.metis.domain;

import java.time.ZonedDateTime;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;

import org.jspecify.annotations.Nullable;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonInclude;

import de.tum.cit.aet.artemis.core.domain.Parent;

/**
 * Per-exercise configuration of Metis, the comprehension check that asks each student a few questions about their own
 * solution after the due date of a programming exercise. The questions are generated by an LLM from the student's git
 * diff, the student answers them inside a per-question timer and an instructor-defined time window, and the LLM rates
 * every answer on a Likert scale with a rationale and may ask follow-up questions when an answer is weak. Instructors
 * switch the check on per exercise, may require a review of the generated questions, and tune how many questions are
 * asked, how long an answer may take and how demanding the questions should be.
 *
 * <p>
 * A permanent configuration row: every programming exercise owns exactly one, from the moment it is stored, whether or not
 * the Metis module is enabled on the server. Since the repositories of this module exist only while it is enabled, the
 * exercise module inserts the row with the column defaults when it stores the exercise ({@code ExerciseConfigurationService}
 * through {@code ExerciseDefaultConfigurationsRepository}), and the changelog gave every programming exercise that existed
 * before its row. The next update of an exercise whose creation failed half-way adds the row that creation left out.
 * Switching the check on or off only changes {@link #enabled}; a setting never inserts or deletes the row.
 * The primary key is the exercise id itself, which expresses the one-to-one in the schema and needs no additional unique
 * index; the exercise has no field pointing back here. The row cascades away with its exercise.
 *
 * <p>
 * Version 1 is formative: the check writes no Result and no grade.
 */
@Entity
@Table(name = "metis_exercise_config")
@JsonInclude(JsonInclude.Include.NON_EMPTY)
public class MetisExerciseConfig {

    /** Lowest value of the five-step scales {@link #answerLength} and {@link #complexity}. */
    public static final int MIN_SCALE_VALUE = 1;

    /** Highest value of the five-step scales {@link #answerLength} and {@link #complexity}. */
    public static final int MAX_SCALE_VALUE = 5;

    /** The smaller of the two Likert scales the LLM may rate answers on, five points, and the default. */
    public static final int MIN_LIKERT_POINTS = 5;

    /** The larger of the two Likert scales the LLM may rate answers on, seven points. No scale between the two is supported. */
    public static final int MAX_LIKERT_POINTS = 7;

    /**
     * The exercise this configuration belongs to, and at the same time the primary key of the row. A parent: the
     * configuration has no meaning without its exercise and cascades away with it.
     */
    @Id
    @Column(name = "exercise_id", nullable = false)
    @Parent
    private Long exerciseId;

    /** Whether the check runs for this exercise. Switching it off keeps the row, so the other settings survive. */
    @Column(name = "enabled", nullable = false)
    private boolean enabled = false;

    /** Start of the default time window in which students may take the check, or null to start at the due date. */
    @Nullable
    @Column(name = "window_start")
    private ZonedDateTime windowStart;

    /** End of the default time window, or null for no end. */
    @Nullable
    @Column(name = "window_end")
    private ZonedDateTime windowEnd;

    /** How many main questions are generated per student. */
    @Column(name = "main_question_count", nullable = false)
    private int mainQuestionCount = 3;

    /** How many follow-up questions may be asked for one main question. */
    @Column(name = "max_follow_ups_per_question", nullable = false)
    private int maxFollowUpsPerQuestion = 2;

    /** Lower bound of the per-question time limit; the LLM picks a limit inside [min, max]. */
    @Column(name = "min_seconds_per_question", nullable = false)
    private int minSecondsPerQuestion = 60;

    /** Upper bound of the per-question time limit; the LLM picks a limit inside [min, max]. */
    @Column(name = "max_seconds_per_question", nullable = false)
    private int maxSecondsPerQuestion = 300;

    /** Expected length of an answer on a scale from 1 (much shorter) to 5 (much longer); 3 is neutral. */
    @Min(MIN_SCALE_VALUE)
    @Max(MAX_SCALE_VALUE)
    @Column(name = "answer_length", nullable = false)
    private int answerLength = 3;

    /** Demand of the questions on a scale from 1 (much simpler) to 5 (much more complex); 3 is neutral. */
    @Min(MIN_SCALE_VALUE)
    @Max(MAX_SCALE_VALUE)
    @Column(name = "complexity", nullable = false)
    private int complexity = 3;

    /**
     * Number of points of the Likert scale the LLM rates answers on: {@value #MIN_LIKERT_POINTS} or {@value #MAX_LIKERT_POINTS},
     * nothing in between, which {@link #isLikertScaleSupported()} checks.
     */
    @Column(name = "likert_scale_points", nullable = false)
    private int likertScalePoints = MIN_LIKERT_POINTS;

    /** A score at or below this value triggers a follow-up question. */
    @Column(name = "follow_up_threshold", nullable = false)
    private int followUpThreshold = 3;

    /** Whether generated questions wait for instructor approval before students see them. */
    @Column(name = "review_required", nullable = false)
    private boolean reviewRequired = false;

    /** Free text handed to the LLM, for example learning goals to focus on or files to avoid. */
    @Nullable
    @Column(name = "instructor_hint")
    private String instructorHint;

    public Long getExerciseId() {
        return exerciseId;
    }

    public void setExerciseId(Long exerciseId) {
        this.exerciseId = exerciseId;
    }

    public boolean isEnabled() {
        return enabled;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }

    @Nullable
    public ZonedDateTime getWindowStart() {
        return windowStart;
    }

    public void setWindowStart(@Nullable ZonedDateTime windowStart) {
        this.windowStart = windowStart;
    }

    @Nullable
    public ZonedDateTime getWindowEnd() {
        return windowEnd;
    }

    public void setWindowEnd(@Nullable ZonedDateTime windowEnd) {
        this.windowEnd = windowEnd;
    }

    public int getMainQuestionCount() {
        return mainQuestionCount;
    }

    public void setMainQuestionCount(int mainQuestionCount) {
        this.mainQuestionCount = mainQuestionCount;
    }

    public int getMaxFollowUpsPerQuestion() {
        return maxFollowUpsPerQuestion;
    }

    public void setMaxFollowUpsPerQuestion(int maxFollowUpsPerQuestion) {
        this.maxFollowUpsPerQuestion = maxFollowUpsPerQuestion;
    }

    public int getMinSecondsPerQuestion() {
        return minSecondsPerQuestion;
    }

    public void setMinSecondsPerQuestion(int minSecondsPerQuestion) {
        this.minSecondsPerQuestion = minSecondsPerQuestion;
    }

    public int getMaxSecondsPerQuestion() {
        return maxSecondsPerQuestion;
    }

    public void setMaxSecondsPerQuestion(int maxSecondsPerQuestion) {
        this.maxSecondsPerQuestion = maxSecondsPerQuestion;
    }

    public int getAnswerLength() {
        return answerLength;
    }

    public void setAnswerLength(int answerLength) {
        this.answerLength = answerLength;
    }

    public int getComplexity() {
        return complexity;
    }

    public void setComplexity(int complexity) {
        this.complexity = complexity;
    }

    public int getLikertScalePoints() {
        return likertScalePoints;
    }

    public void setLikertScalePoints(int likertScalePoints) {
        this.likertScalePoints = likertScalePoints;
    }

    /**
     * Whether the number of Likert points is one of the two supported scales. A range from five to seven would also admit six,
     * a scale no rating is defined for, so Bean Validation checks membership instead. The database refuses any other value as
     * well, for the writes that do not pass through validation.
     *
     * @return true for {@value #MIN_LIKERT_POINTS} or {@value #MAX_LIKERT_POINTS} points
     */
    @JsonIgnore
    @AssertTrue(message = "A Likert scale has " + MIN_LIKERT_POINTS + " or " + MAX_LIKERT_POINTS + " points")
    public boolean isLikertScaleSupported() {
        return likertScalePoints == MIN_LIKERT_POINTS || likertScalePoints == MAX_LIKERT_POINTS;
    }

    public int getFollowUpThreshold() {
        return followUpThreshold;
    }

    public void setFollowUpThreshold(int followUpThreshold) {
        this.followUpThreshold = followUpThreshold;
    }

    public boolean isReviewRequired() {
        return reviewRequired;
    }

    public void setReviewRequired(boolean reviewRequired) {
        this.reviewRequired = reviewRequired;
    }

    @Nullable
    public String getInstructorHint() {
        return instructorHint;
    }

    public void setInstructorHint(@Nullable String instructorHint) {
        this.instructorHint = instructorHint;
    }
}
