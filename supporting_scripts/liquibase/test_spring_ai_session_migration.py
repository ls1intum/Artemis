"""Exercise the copy of the Atlas chat history to the Spring AI session tables against populated PostgreSQL and MySQL databases.

Run with Docker available: python3 supporting_scripts/liquibase/test_spring_ai_session_migration.py
Uses the same pinned Liquibase image and JDBC drivers as verify_schema.py.
"""

import argparse
from pathlib import Path
import shutil
import tempfile
import unittest

from verify_schema import Database, ENGINES, LIQUIBASE_DIR, Liquibase, ensure_drivers, run

CHANGELOG = "20261124081403_changelog.xml"


class SpringAiSessionMigrationTest(unittest.TestCase):
    databases = tuple(ENGINES)

    def test_copies_the_conversations_in_their_order_and_leaves_system_and_tool_rows(self):
        ensure_drivers()
        with tempfile.TemporaryDirectory(prefix="spring-ai-session-migration-") as directory:
            workspace = Path(directory)
            shutil.copy2(LIQUIBASE_DIR / "changelog" / CHANGELOG, workspace / CHANGELOG)
            for offset, name in enumerate(self.databases):
                engine = ENGINES[name]
                with self.subTest(database=engine.name), Database(engine, "spring-ai-session-data", 15900 + offset) as database:
                    self.sql(database, self.old_table(engine.name) + """
                        INSERT INTO spring_ai_chat_memory (conversation_id, content, timestamp, sequence_id, type) VALUES
                            ('course_1_user_1', 'second question', '2026-11-20 10:01:00', 2, 'USER'),
                            ('course_1_user_1', 'first question', '2026-11-20 10:00:00', 0, 'USER'),
                            ('course_1_user_1', 'first answer', '2026-11-20 10:00:05', 1, 'ASSISTANT'),
                            ('course_1_user_1', 'second answer', '2026-11-20 10:01:09', 3, 'ASSISTANT'),
                            ('course_1_user_1', 'internal system text', '2026-11-20 10:01:10', 4, 'SYSTEM'),
                            ('course_1_user_1', 'tool result', '2026-11-20 10:01:11', 5, 'TOOL'),
                            ('course_2_user_1', 'a question in another course', '2026-11-21 09:00:00', 0, 'USER'),
                            ('course_2_user_1', 'a quote '' and a line\nbreak', '2026-11-21 09:00:02', 1, 'ASSISTANT'),
                            ('course_3_user_1', 'only a system message', '2026-11-22 09:00:00', 0, 'SYSTEM');
                    """)
                    Liquibase(workspace).apply(database, CHANGELOG)
                    # One session per conversation with a message of a user or the assistant, none for the conversation of a system message only
                    self.assertEqual(self.sql(database, "SELECT id, event_version FROM AI_SESSION ORDER BY id;"), "course_1_user_1\t4\ncourse_2_user_1\t2")
                    self.assertEqual(self.sql(database, "SELECT COUNT(*) FROM AI_SESSION WHERE expires_at > created_at;"), "2")
                    # The order of the old sequence decides, not the order of the rows. The type and the text arrive as they were
                    self.assertEqual(self.sql(database, """
                        SELECT session_id, message_type, message_content FROM AI_SESSION_EVENT
                        WHERE session_id = 'course_1_user_1' ORDER BY seq;
                    """), "course_1_user_1\tUSER\tfirst question\ncourse_1_user_1\tASSISTANT\tfirst answer\n"
                          "course_1_user_1\tUSER\tsecond question\ncourse_1_user_1\tASSISTANT\tsecond answer")
                    # The text of a message with a quote and a line break arrives unchanged
                    self.assertEqual(self.sql(database, """
                        SELECT message_content FROM AI_SESSION_EVENT WHERE session_id = 'course_2_user_1' ORDER BY seq;
                    """), "a question in another course\na quote ' and a line\nbreak")
                    self.assertEqual(self.sql(database, "SELECT COUNT(*) FROM AI_SESSION_EVENT WHERE message_type NOT IN ('USER', 'ASSISTANT');"), "0")
                    # Every event reads as a message event with an empty payload, and its id is unique
                    self.assertEqual(self.sql(database, """
                        SELECT COUNT(*), COUNT(DISTINCT id) FROM AI_SESSION_EVENT
                        WHERE event_type = 'MESSAGE' AND payload = '{}' AND metadata = '{}' AND synthetic = FALSE;
                    """), "6\t6")
                    # The old table is not touched
                    self.assertEqual(self.sql(database, "SELECT COUNT(*) FROM spring_ai_chat_memory;"), "9")

    @staticmethod
    def old_table(engine):
        # The columns of spring_ai_chat_memory as the baseline and the changelog 20260611220000 left them
        if engine == "postgres":
            return """
                CREATE TABLE spring_ai_chat_memory (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id VARCHAR(255) NOT NULL, content TEXT NOT NULL,
                    timestamp TIMESTAMP(3) NOT NULL, sequence_id BIGINT NOT NULL DEFAULT 0, type TEXT NOT NULL
                );
            """
        return """
            CREATE TABLE spring_ai_chat_memory (
                id BIGINT AUTO_INCREMENT PRIMARY KEY, conversation_id VARCHAR(255) NOT NULL, content TEXT NOT NULL,
                `timestamp` DATETIME(3) NOT NULL, sequence_id BIGINT NOT NULL DEFAULT 0, type ENUM('USER','ASSISTANT','SYSTEM','TOOL') NOT NULL
            );
        """

    def sql(self, database, query):
        if database.engine.name == "postgres":
            client = ["psql", "-U", "artemis", "-d", "Artemis", "-t", "-A", "-F", "\t", "-v", "ON_ERROR_STOP=1"]
        else:
            client = ["mysql", "--default-character-set=utf8mb4", "-u", "root", "-N", "-B", "--raw", "--database", "Artemis"]
        result = run(["docker", "exec", "-i", database.container, *client], input=query)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--database", choices=ENGINES)
    arguments, unittest_arguments = parser.parse_known_args()
    if arguments.database:
        SpringAiSessionMigrationTest.databases = (arguments.database,)
    unittest.main(argv=[__file__, *unittest_arguments], verbosity=2)
