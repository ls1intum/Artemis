#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(import.meta.dirname, '..');

export function renderReferencePage(index) {
    if (!index?.entries || typeof index.entries !== 'object' || Array.isArray(index.entries)) {
        throw new Error('Storybook index.json does not contain an entries object');
    }
    const components = [
        ...new Set(
            Object.values(index.entries)
                .filter((entry) => entry.type === 'docs' && entry.title !== 'Introduction')
                .map((entry) => entry.title),
        ),
    ].sort((first, second) => first.localeCompare(second));
    const componentList = components.map((title) => `- ${title.replace('/', ' — ')}`).join('\n');

    return `---
id: tum-ui
slug: /tum-ui-reference
title: TUM UI component reference
description: Browse the existing TUM UI package components, supported states, accessibility checks, and APIs.
pagination_prev: null
pagination_next: null
custom_edit_url: null
---

import StorybookRedirect from '../../src/components/StorybookRedirect/StorybookRedirect';

{/* Generated by supporting_scripts/generate-tum-ui-reference-page.mjs. */}

# TUM UI component reference

<StorybookRedirect />

The component reference is included in the combined Artemis documentation:

\`\`\`bash
pnpm run docs:build
pnpm run docs:serve
\`\`\`

For component development with live updates, run:

\`\`\`bash
pnpm --dir packages/tum-ui run storybook
\`\`\`

## Available components

${componentList}
`;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
    const indexPath = resolve(root, process.argv[2] ?? 'build/documentation-static/developer/tum-ui/index.json');
    const outputPath = resolve(root, 'documentation/docs/developer/tum-ui.mdx');
    const page = renderReferencePage(JSON.parse(readFileSync(indexPath, 'utf8')));
    if (process.env.CI === 'true') {
        if (readFileSync(outputPath, 'utf8') !== page) {
            throw new Error('TUM UI reference page is stale; run pnpm run docs:build locally and commit the generated page');
        }
    } else if (readFileSync(outputPath, 'utf8') !== page) {
        writeFileSync(outputPath, page);
    }
}
