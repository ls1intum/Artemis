#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(import.meta.dirname, '..');

function referenceComponents(index) {
    if (!index?.entries || typeof index.entries !== 'object' || Array.isArray(index.entries)) {
        throw new Error('Storybook index.json does not contain an entries object');
    }
    return Object.values(index.entries)
        .filter((entry) => entry.type === 'docs' && entry.title !== 'Introduction')
        .map((entry) => ({
            id: entry.id,
            title: entry.title,
            label: entry.title.replace('/', ': '),
            anchor: entry.id.replace(/--docs$/, ''),
        }))
        .filter((entry, index, entries) => entries.findIndex(({ title }) => title === entry.title) === index)
        .sort((first, second) => first.title.localeCompare(second.title));
}

export function renderReferencePage(index) {
    const components = referenceComponents(index);
    const componentList = components.map(({ label }) => `### ${label}`).join('\n\n');

    return `---
id: tum-ui
slug: /tum-ui-reference
title: TUM UI component reference
description: Browse the reusable TUM UI design-system components, supported states, accessibility checks, and APIs.
pagination_prev: null
pagination_next: null
custom_edit_url: null
---

import StorybookRedirect from '../../src/components/StorybookRedirect/StorybookRedirect';

{/* Generated by supporting_scripts/generate-tum-ui-reference-page.mjs. */}

# TUM UI component reference

<StorybookRedirect />

TUM UI is the target Artemis component system. Browse or search for a component here before adding
another abstraction. The reference opens the package Storybook with supported states, controls,
interaction examples, accessibility results, and generated APIs.

The component reference is included in the combined Artemis documentation:

\`\`\`bash
pnpm run docs:build
pnpm run docs:serve
\`\`\`

For component development with live updates, run:

\`\`\`bash
pnpm --dir packages/tum-ui run storybook
\`\`\`

## Available components

${componentList}
`;
}

export function renderReferenceMap(index) {
    const references = Object.fromEntries(referenceComponents(index).map(({ anchor, id }) => [anchor, id]));
    const entries = Object.entries(references)
        .map(([anchor, id]) => `    '${anchor.replaceAll("'", "\\'")}': '${id.replaceAll("'", "\\'")}',`)
        .join('\n');
    return `// Generated by supporting_scripts/generate-tum-ui-reference-page.mjs.
export const STORYBOOK_REFERENCES: Readonly<Record<string, string>> = {
${entries}
};
`;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
    const indexPath = resolve(root, process.argv[2] ?? 'build/documentation-static/developer/tum-ui/index.json');
    const index = JSON.parse(readFileSync(indexPath, 'utf8'));
    const outputs = [
        {
            path: resolve(root, 'documentation/docs/developer/tum-ui.mdx'),
            content: renderReferencePage(index),
        },
        {
            path: resolve(root, 'documentation/src/components/StorybookRedirect/storybook-references.ts'),
            content: renderReferenceMap(index),
        },
    ];
    for (const output of outputs) {
        if (process.env.CI === 'true') {
            if (readFileSync(output.path, 'utf8') !== output.content) {
                throw new Error('TUM UI reference files are stale; run pnpm run docs:build locally and commit the generated files');
            }
        } else if (readFileSync(output.path, 'utf8') !== output.content) {
            writeFileSync(output.path, output.content);
        }
    }
}
