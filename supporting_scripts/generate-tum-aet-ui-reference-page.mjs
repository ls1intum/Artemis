#!/usr/bin/env node

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const storybookDocsId = /^[a-z0-9]+(?:-[a-z0-9]+)*--docs$/;

function referenceComponents(index) {
    if (!index?.entries || typeof index.entries !== 'object' || Array.isArray(index.entries)) {
        throw new Error('Storybook index.json does not contain an entries object');
    }
    return Object.values(index.entries)
        .filter((entry) => entry.type === 'docs' && entry.title !== 'Introduction')
        .map((entry) => {
            if (!storybookDocsId.test(entry.id)) {
                throw new Error(`Unsupported Storybook documentation id: ${entry.id}`);
            }
            return {
                id: entry.id,
                anchor: entry.id.slice(0, -'--docs'.length),
                title: entry.title,
                label: entry.title.replace('/', ': '),
            };
        })
        .filter((entry, index, entries) => entries.findIndex(({ title }) => title === entry.title) === index)
        .sort((first, second) => first.title.localeCompare(second.title));
}

export function renderReferencePage(index) {
    const components = referenceComponents(index);
    const componentList = components.map(({ label }) => `### ${label}`).join('\n\n');

    return `---
id: tum-aet-ui
title: TUM AET UI component reference
sidebar_label: TUM AET UI component reference
slug: /tum-aet-ui-reference
description: Browse the Angular components from the Applied Education Technologies research group at TUM.
pagination_prev: null
pagination_next: null
custom_edit_url: null
---

import StorybookRedirect from '../../src/components/StorybookRedirect/StorybookRedirect';

{/* Generated by supporting_scripts/generate-tum-aet-ui-reference-page.mjs. */}

<StorybookRedirect />

TUM AET UI is the component library from the Applied Education Technologies (AET) research group
at the Technical University of Munich. It is used by Artemis. This reference opens the package
Storybook with supported states, controls, interaction examples, accessibility results, and APIs.

The component reference is included in the combined Artemis documentation:

\`\`\`bash
pnpm run docs:build
pnpm run docs:serve
\`\`\`

For component development with live updates, run:

\`\`\`bash
pnpm --dir packages/tum-aet-ui run storybook
\`\`\`

## Available components

${componentList}
`;
}

export function renderReferenceResolver(index) {
    const cases = referenceComponents(index)
        .map(({ anchor, id }) => `        case '${anchor}':\n            return '${id}';`)
        .join('\n');

    return `// Generated by supporting_scripts/generate-tum-aet-ui-reference-page.mjs.
const DEFAULT_STORY = 'introduction--docs';

export function storybookStoryFromHash(hash: string): string {
    let anchor: string;
    try {
        anchor = decodeURIComponent(hash.startsWith('#') ? hash.slice(1) : hash);
    } catch {
        return DEFAULT_STORY;
    }

    switch (anchor) {
${cases}
        default:
            return DEFAULT_STORY;
    }
}
`;
}

if (resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)) {
    const indexPath = resolve(root, process.argv[2] ?? 'build/documentation-static/developer/tum-aet-ui/index.json');
    const index = JSON.parse(readFileSync(indexPath, 'utf8'));
    const outputs = [
        {
            path: resolve(root, 'documentation/docs/developer/tum-aet-ui.mdx'),
            content: renderReferencePage(index),
        },
        {
            path: resolve(root, 'documentation/src/components/StorybookRedirect/storybook-reference.generated.ts'),
            content: renderReferenceResolver(index),
        },
    ];
    for (const output of outputs) {
        if (process.env.CI === 'true') {
            if (readFileSync(output.path, 'utf8') !== output.content) {
                throw new Error('TUM AET UI reference files are stale; run pnpm run docs:build locally and commit the generated files');
            }
        } else if (readFileSync(output.path, 'utf8') !== output.content) {
            writeFileSync(output.path, output.content);
        }
    }
}
